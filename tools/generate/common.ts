// Shared text + naming helpers used by the emitters.
// Keep this dependency-free: it is the lowest layer of the generator.

/** PascalCase a snake/kebab name: "proposal_source" -> "ProposalSource". */
export function pascal(s: string): string {
  return s
    .split(/[-_]/)
    .map((w) => (w ? w[0].toUpperCase() + w.slice(1) : w))
    .join("");
}

/** Top-level named type -> exported class/type name: "note" -> "EtkNote". */
export function typeName(named: string): string {
  return "Etk" + pascal(named);
}

/** Do-not-edit banner lines for a `//` or `#` comment language. */
export function banner(comment: string): string[] {
  return [
    `${comment} GENERATED by tools/generate - do not edit by hand.`,
    `${comment} Source of truth: schemas/etk/*.yaml. Regenerate with: just generate.`,
    `${comment}`,
  ];
}

/** Collapse a multi-line description to one line (for doc comments). */
export function oneLine(s: string): string {
  return s.replace(/\s+/g, " ").trim();
}

/** A JS/TS regex literal from a pattern string (escaping embedded slashes). */
export function regexLit(pattern: string): string {
  return `/${pattern.replace(/\//g, "\\/")}/`;
}
